export type Digicore = (typeof DIGICORES)[number];

const DIGICORE_SET = new Set<string>(DIGICORES);
export const isDigicore = (v: unknown): v is Digicore => typeof v === 'string' && DIGICORE_SET.has(v);

// 이미지 파일명에는 ':'를 쓸 수 없어 '_'로 저장돼 있으므로 주소를 만들 때만 바꿉니다.
export const digicoreImage = (name: string) =>
  `https://media.dsrwiki.com/dsrwiki/item/${encodeURIComponent(name.replace(/:/g, '_'))}.png`;

/** "부서진 듀크몬:크림슨모드 디지코어" → "듀크몬:크림슨모드" */
export const digicoreShortName = (name: string) =>
  name.replace(/^부서진\s+/, '').replace(/\s+디지코어$/, '');

/** 검색용: 공백/콜론/기호 제거 ("듀크몬 크림슨", "듀크몬:크림슨" 모두 찾기) */
export const digicoreSearchKey = (name: string) =>
  digicoreShortName(name).replace(/[\s_:\-()]/g, '').toLowerCase();
