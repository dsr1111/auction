// Isolated PostgreSQL/WASM integration test. Never connects to the deployed DB.
// Install test engine: npm install --prefix .membership-test-tools --no-save --package-lock=false --ignore-scripts @electric-sql/pglite@0.5.11
// Run: node scripts/test-membership-db.cjs
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('../.membership-test-tools/node_modules/@electric-sql/pglite');

async function main() {
  const db = new PGlite();
  let checks = 0;
  const admin = '100000000000000001';
  const alice = '100000000000000002';
  const bob = '100000000000000003';
  const carol = '100000000000000004';
  const dana = '100000000000000005';
  const command = async (actor, action, data) => (await db.query('select public.auction_membership_command($1,$2,$3) as result', [actor,action,JSON.stringify(data)])).rows[0].result;
  const scalar = async sql => Object.values((await db.query(sql)).rows[0])[0];
  const fail = async (fn, pattern) => { await assert.rejects(fn, pattern); checks++; };
  const bid = async (user, guild = 'guild1', amount = 20000, quantity = 1) => (await db.query(`insert into public.${guild === 'guild1' ? 'bid_history' : 'bid_history_guild2'} (item_id,bid_amount,bid_quantity,bidder_nickname,bidder_discord_id) values (1,$1,$2,'테스트',$3) returning id`, [amount,quantity,user])).rows[0].id;
  const assign = (userId, guildType, version = 0) => command(admin, 'assign', { userId,guildType,nickname:'테스트',version,reason:'테스트 등록' });
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create table public.items (id bigint primary key,name text not null,price numeric not null,quantity integer,end_time timestamptz,current_bid numeric,last_bidder_nickname text);
      create table public.items_guild2 (id integer primary key,name text not null,price integer not null,quantity integer,end_time timestamptz,current_bid integer,last_bidder_nickname text);
      create table public.bid_history (id integer generated by default as identity primary key,item_id integer not null references public.items(id),bid_amount integer not null,bid_quantity integer,bidder_nickname text not null,bidder_discord_id text,bidder_discord_name text,created_at timestamptz default now());
      create table public.bid_history_guild2 (id integer generated by default as identity primary key,item_id integer not null references public.items_guild2(id),bid_amount integer not null,bid_quantity integer,bidder_nickname text not null,bidder_discord_id text,bidder_discord_name text,created_at timestamptz default now());
      grant all on all tables in schema public to service_role;
      grant usage, select on all sequences in schema public to service_role;
      insert into items values(1,'세계수 품목',10000,3,now()+interval '1 hour',10000,null);
      insert into items_guild2 values(1,'크랙 품목',10000,3,now()+interval '1 hour',10000,null);
    `);
    const migration = fs.readFileSync(path.join(__dirname,'../supabase/migrations/20261021151116_guild_membership_approval.sql'),'utf8');
    await db.exec(migration);
    checks++;
    assert.equal(await scalar('select enforcement_enabled from auction_membership_settings'),false); checks++;
    for (const role of ['anon','authenticated']) {
      await db.exec(`set role ${role}`);
      await fail(() => db.query('select * from auction_memberships'), /permission denied/);
      await fail(() => command(alice,'assign',{userId:alice,guildType:'guild1',nickname:'fake',version:0,reason:'fake'}), /permission denied/);
      await db.exec('reset role');
    }
    await db.exec('set role service_role');
    await fail(() => db.query('delete from guild_membership_events'), /permission denied/);
    await fail(() => db.query('update guild_membership_events set reason = \'fake\''), /permission denied/);

    const request = await command(alice,'apply',{guildType:'guild1',nickname:'앨리스',reason:'가입',requesterName:'Alice'});
    await fail(() => command(alice,'apply',{guildType:'guild2',nickname:'앨리스'}), /이미 승인 대기/);
    await fail(() => command(bob,'cancel',{requestId:request.id}), /이미 처리되었거나/);
    await command(admin,'approve',{requestId:request.id,reason:''});
    await fail(() => command(admin,'approve',{requestId:request.id,reason:''}), /이미 처리되었거나/);
    assert.equal(await scalar(`select guild_type from auction_memberships where user_id='${alice}'`),'guild1'); checks++;

    // Preparation preserves existing bidding, but suspensions still take effect.
    const oldWrongBid = await bid(alice,'guild2');
    const activeBid = await bid(alice);
    const transfer = await command(alice,'apply',{guildType:'guild2',nickname:'앨리스',reason:'이전'});
    await fail(() => command(admin,'approve',{requestId:transfer.id,reason:''}), /진행 중인 입찰/);
    await fail(() => assign(alice,'guild2',1), /진행 중인 입찰/);
    await command(alice,'cancel',{requestId:transfer.id});
    const suspended = await command(admin,'suspend',{userId:alice,version:1,reason:'정지 테스트'});
    assert.equal(suspended.version,2); checks++;
    await fail(() => bid(alice), /정지/);
    await fail(() => command(alice,'apply',{guildType:'guild2',nickname:'테스트'}), /정지/);
    await fail(() => command(admin,'resume',{userId:alice,version:1,reason:'낡은 버전'}), /다른 관리자가/);
    await command(admin,'resume',{userId:alice,version:2,reason:'해제'});

    await assign(bob,'guild2');
    const pending = await command(bob,'apply',{guildType:'guild1',nickname:'밥',reason:'변경'});
    await assign(bob,'guild2',1);
    await fail(() => command(admin,'approve',{requestId:pending.id,reason:''}), /소속 정보가 변경/);
    await fail(() => command(admin,'reject',{requestId:pending.id,reason:''}), /반려 사유/);
    await command(admin,'reject',{requestId:pending.id,reason:'다시 신청해주세요'});
    const again = await command(bob,'apply',{guildType:'guild1',nickname:'밥',reason:''});
    await command(bob,'cancel',{requestId:again.id}); checks++;

    const foreign = await bid(carol,'guild2');
    await fail(() => assign(carol,'guild1'), /진행 중인 입찰/);
    await db.query('delete from bid_history_guild2 where id=$1',[foreign]);
    await assign(carol,'guild1');

    // Upgrade an existing preparation installation while auctions are still open.
    // Preserve all memberships, live bids, pending requests, and pause state.
    const pendingAtUpgrade = await command(dana,'apply',{guildType:'guild1',nickname:'대기자',reason:''});
    const bidCountAtUpgrade = await scalar('select count(*) from bid_history');
    await command(admin,'pause',{reason:'업그레이드 점검'});
    await db.exec('reset role');
    await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations/20261021234857_immediate_guild_membership.sql'),'utf8'));
    await db.exec('set role service_role');
    assert.equal(await scalar('select enforcement_enabled from auction_membership_settings'),true); checks++;
    assert.equal(await scalar('select bidding_paused from auction_membership_settings'),true); checks++;
    assert.equal(await scalar('select count(*) from bid_history'),bidCountAtUpgrade); checks++;
    assert.equal(await scalar(`select status from guild_membership_requests where id=${pendingAtUpgrade.id}`),'pending'); checks++;
    await fail(()=>db.query('update auction_membership_settings set enforcement_enabled=false'),/check constraint/);
    await command(admin,'resume_bidding',{reason:'점검 완료'});
    await fail(()=>bid(dana),/승인된 소속 길드/);
    await db.exec("update items set end_time=now()-interval '1 second'; update items_guild2 set end_time=now()-interval '1 second'");
    await fail(() => bid(alice), /마감/);
    await fail(() => command(admin,'enforce',{reason:'중복'}), /이미 소속 제한/);
    await db.exec("update items set end_time=now()+interval '1 hour'; update items_guild2 set end_time=now()+interval '1 hour'");
    await bid(alice);
    await bid(bob,'guild2');
    await fail(() => bid(alice,'guild2'), /승인된 소속 길드/);
    await fail(() => bid(bob,'guild1'), /승인된 소속 길드/);
    await fail(() => bid(admin), /승인된 소속 길드/); // No administrator exception.
    await fail(() => bid(dana), /승인된 소속 길드/);
    await fail(() => db.query('update bid_history_guild2 set bid_amount=30000 where id=$1',[oldWrongBid]), /승인된 소속 길드/);
    await db.query('delete from bid_history_guild2 where id=$1',[oldWrongBid]); checks++;
    await fail(() => db.query('update bid_history set bidder_discord_id=$1 where id=$2',[bob,activeBid]), /소유자/);
    await fail(() => bid(alice,'guild1',10001), /10,000bit/);
    await fail(() => bid(alice,'guild1',20000,4), /수량/);
    await bid(bob,'guild2'); await bid(bob,'guild2');
    await fail(() => bid(bob,'guild2'), /3회/);

    await command(admin,'pause',{reason:'점검'});
    await fail(() => bid(alice), /일시 중지/);
    await db.query('update bid_history set bid_amount=30000 where id=$1',[activeBid]); checks++;
    await command(admin,'resume_bidding',{reason:'점검 완료'});
    assert.equal(await scalar('select enforcement_enabled from auction_membership_settings'),true); checks++;
    await bid(alice);

    // After auction close, transfer preserves all historical bids, and is atomic with audit.
    await db.exec("update items set end_time=now()-interval '1 second'");
    const beforeCount = await scalar(`select count(*) from bid_history where bidder_discord_id='${alice}'`);
    const changed = await assign(alice,'guild2',3);
    assert.equal(changed.guild_type,'guild2'); checks++;
    assert.equal(await scalar(`select count(*) from bid_history where bidder_discord_id='${alice}'`),beforeCount); checks++;
    await db.exec('reset role; revoke insert on guild_membership_events from service_role; set role service_role');
    await fail(() => command(admin,'suspend',{userId:alice,version:4,reason:'감사 저장 실패'}), /permission denied/);
    assert.equal(await scalar(`select status from auction_memberships where user_id='${alice}'`),'active'); checks++;
    assert.equal(await scalar(`select version from auction_memberships where user_id='${alice}'`),4); checks++;
    await db.exec('reset role');
    const rls = await db.query("select relname,relrowsecurity from pg_class where relname in ('auction_memberships','guild_membership_requests','guild_membership_events','auction_membership_settings')");
    assert.equal(rls.rows.length,4); assert.ok(rls.rows.every(row => row.relrowsecurity)); checks++;

    // A capability migration must not remove existing memberships on deployment.
    const beforeUpgrade = await scalar('select count(*) from auction_memberships');
    await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations/20261022102548_remove_guild_membership.sql'),'utf8'));
    assert.equal(await scalar('select count(*) from auction_memberships'),beforeUpgrade); checks++;
    const remove = (userId,version,reason='탈퇴 요청') => db.query('select public.auction_membership_remove($1,$2,$3,$4)',[admin,userId,version,reason]);
    for(const role of ['anon','authenticated']) {
      await db.exec(`set role ${role}`);
      await fail(()=>remove(bob,2),/permission denied/);
      await fail(()=>db.query('delete from auction_memberships'),/permission denied/);
      await db.exec('reset role');
    }
    await db.exec('grant insert on guild_membership_events to service_role; set role service_role');
    const pendingRemoval = await command(bob,'apply',{guildType:'guild1',nickname:'이전 신청'});
    const bidsBeforeRemoval = await db.query('select * from bid_history_guild2 order by id');
    await fail(()=>remove(bob,1),/소속 정보가 변경/);
    await fail(()=>remove(bob,2,' '),/소속 삭제 사유/);
    await db.exec('reset role; revoke insert on guild_membership_events from service_role; set role service_role');
    await fail(()=>remove(bob,2),/permission denied/);
    assert.equal(await scalar(`select version from auction_memberships where user_id='${bob}'`),2); checks++;
    assert.equal(await scalar(`select status from guild_membership_requests where id=${pendingRemoval.id}`),'pending'); checks++;
    await db.exec('reset role; grant insert on guild_membership_events to service_role; set role service_role');
    await remove(bob,2);
    assert.equal(Number(await scalar(`select count(*) from auction_memberships where user_id='${bob}'`)),0); checks++;
    assert.equal(await scalar(`select status from guild_membership_requests where id=${pendingRemoval.id}`),'cancelled'); checks++;
    assert.deepEqual((await db.query('select * from bid_history_guild2 order by id')).rows,bidsBeforeRemoval.rows); checks++;
    const audit=(await db.query("select * from guild_membership_events where user_id=$1 and action='remove'",[bob])).rows[0];
    assert.equal(audit.before_state.guild_type,'guild2'); assert.equal(audit.after_state,null); assert.equal(audit.actor_id,admin); checks++;
    await fail(()=>bid(bob,'guild2'),/승인된 소속 길드/);
    await fail(()=>remove(bob,2),/이미 소속이 삭제/);
    await fail(()=>command(admin,'approve',{requestId:pendingRemoval.id,reason:''}),/이미 처리되었거나/);
    const reapplied=await command(bob,'apply',{guildType:'guild2',nickname:'재가입'});
    const reapproved=await command(admin,'approve',{requestId:reapplied.id,reason:''});
    assert.ok(reapproved.version>2); assert.equal(reapproved.status,'active'); checks++;
    await fail(()=>remove(bob,2),/소속 정보가 변경/);
    await fail(()=>assign(bob,'guild2',2),/다른 관리자가/);
    // Legacy suspended accounts are not silently converted, but can be removed.
    await command(admin,'suspend',{userId:carol,version:1,reason:'이전 정지'});
    await remove(carol,2);
    const restored=await assign(carol,'guild1');
    assert.equal(restored.status,'active'); assert.ok(restored.version>2); checks++;
    await fail(()=>db.query('delete from guild_membership_events'),/permission denied/);
    console.log(`PASS: ${checks} isolated PostgreSQL integration checks. No production connection used.`);
  } finally { await db.close(); }
}
main().catch(error => { console.error(error); process.exitCode=1; });
